$scenarioTemplate = @'
using Cerneala.UI.Controls;
using Cerneala.UI.Servo;
using ServoApi = Cerneala.UI.Servo.Servo;

namespace Issue@@N@@;

// The scenario of the reproduction app. ReproHarness.cs (fixed) shows the verdict, runs the invariant check from
// FrameRendered and drives check mode. The sample below is a button that check mode clicks twice; its invariant is
// trivially true, so the generated app builds and exits with 0 unmodified. Replace every member marked FILL IN.
//
// Rules from cerneala-fix-bug, step 5:
//   - public Cerneala API only, as an application would use it;
//   - real input only, through Servo (ClickAsync, DragAsync, ScrollAsync, PressKeyAsync, SendTextAsync), never by
//     assigning control state; give targets an id with ServoApi.SetId;
//   - the verdict comes from live framework state; never hard-code it.
public partial class MainWindow : Window, IReproScenario
{
    private ReproHarness harness = null!;
    private bool initialized;

    private void OnContentRendered(object? sender, EventArgs args)
    {
        if (initialized)
        {
            return;
        }

        initialized = true;
        harness = new ReproHarness(
            this,
            this,
            new ReproView(VerdictLine, FirstFailureLine, TotalsLine, NowLine, ScaleLine, StepLine, StepsText, ExpectedText));
        harness.Start();
    }

    // ===== FILL IN: sample state (replace with what the scenario needs) =====
    private int clicks;
    private int lastCheckedClicks = -1;
    private int checks;

    // FILL IN 1/6, scenario setup: build the issue's real scenario in HostStack or the .crn and give every Servo target an id.
    public void ReproSetUp()
    {
        ServoApi.SetId(SampleButton, "sample-button");
        SampleButton.Click += (_, _) => clicks++;
    }

    // FILL IN 2/6, user steps: the numbered literal actions the user does (same elements, sizes and values as the issue).
    public string ReproUserSteps =>
        "1. Click the sample button.\n2. Click it again.";

    // FILL IN 3/6, what you should see: the literal result when the bug is absent.
    public string ReproExpected =>
        "The top line stays green and the click count follows your clicks.";

    // FILL IN 4/6, change detector: true only when the checked state changed since the last check (must be true at first).
    public bool ReproCheckedStateChanged()
    {
        if (clicks == lastCheckedClicks)
        {
            return false;
        }

        lastCheckedClicks = clicks;
        return true;
    }

    // FILL IN 5/6, invariant: read live state through public API (ArrangedBounds, Root.Scale ...), return pass or fail,
    // the first-failure text with measured and expected values, and the totals. Never hard-code the verdict.
    public ReproCheckResult ReproCheckInvariant()
    {
        checks++;
        bool passed = clicks >= 0; // the sample invariant is trivially true
        return new ReproCheckResult(
            passed,
            passed ? null : $"Click count is {clicks}, expected 0 or more.",
            $"{checks} checks so far.",
            $"Now: the button was clicked {clicks} times.");
    }

    // FILL IN 6/6, check-mode steps: what the user does, but with Servo. Wait for the state each step causes with
    // harness.WaitForStateAsync (it stops after 300 frames with NOT REACHED); never count frames.
    public IReadOnlyList<ReproStep> ReproCheckSteps(ReproHarness harness) =>
    [
        new ReproStep("click the sample button", async servo =>
        {
            await servo.ClickAsync(ServoTarget.ById("sample-button"));
            await harness.WaitForStateAsync(servo, () => clicks == 1, "the first click arrives");
        }),
        new ReproStep("click the sample button again", async servo =>
        {
            await servo.ClickAsync(ServoTarget.ById("sample-button"));
            await harness.WaitForStateAsync(servo, () => clicks == 2, "the second click arrives");
        })
    ];

    // Optional: return a reason when the triggering condition never happened (exit code 2); null means it happened.
    public string? ReproNotReached() => clicks == 2 ? null : $"only {clicks} of 2 clicks arrived";
}
'@

