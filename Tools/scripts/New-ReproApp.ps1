#requires -Version 7.0
<#
.SYNOPSIS
Creates the skeleton of a cerneala-fix-bug reproduction app: a small Cerneala window with a live OK/BUG verdict and a Servo-driven check mode.

.DESCRIPTION
cerneala-fix-bug (step 5) ships every fix with a reproduction app that is built twice, before and after the
fix. This script writes the mechanical part of that app, so that the agent only fills in the scenario:

  Issue<N>.csproj      WinExe, net8.0-windows, references to Cerneala, SdlGpu and SourceGen through $(CernealaRoot),
                       the ReproVariant property (default dev) passed on as AssemblyMetadata.
  BackendRegistration.cs
  ReproHarness.cs      Fixed infrastructure, not meant to be edited: window title from ReproVariant, verdict lines,
                       sticky BUG state, invariant check from FrameRendered, check mode (--check <report>
                       [--frames <folder>]) with Servo, screenshots, report file, exit codes
                       0 = OK, 1 = BUG, 2 = NOT REACHED, 3 = ERROR.
  MainWindow.crn       Verdict area, numbered user steps, "what you should see", scenario host.
  MainWindow.crn.cs    The scenario. It starts as a tiny working sample (a button that check mode clicks), so the
                       generated app builds and exits with 0 unmodified. Members marked "FILL IN" are the ones to change.

The destination must be outside every git working tree. The root Cerneala.csproj globs **\*.crn, and MSBuild
ignores .gitignore, so an app inside a checkout breaks the build of Cerneala with CERNEALAUI003. All template
text lives in this script for the same reason: no .crn or .cs template file may exist in the repository.

.PARAMETER Issue
GitHub issue number of the bug. It names the project (Issue<N>), the namespace and the window title.

.PARAMETER Destination
The app folder, for example <scratchpad>\repro-369\Issue369. It is created when missing.

.PARAMETER CernealaRoot
Root of the Cerneala checkout or worktree the app builds against. Default: git rev-parse --show-toplevel of the current directory.

.PARAMETER Force
Overwrite files that already exist in the destination.

.EXAMPLE
pwsh -NoProfile -File Tools/scripts/New-ReproApp.ps1 -Issue 369 -Destination $env:TEMP/repro-369/Issue369
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory)][int] $Issue,
    [Parameter(Mandatory)][string] $Destination,
    [string] $CernealaRoot,
    [switch] $Force
)

$ErrorActionPreference = 'Stop'

if (-not $CernealaRoot) {
    $CernealaRoot = (& git rev-parse --show-toplevel 2>$null)
    if ($LASTEXITCODE -ne 0 -or -not $CernealaRoot) { throw 'Pass -CernealaRoot: the current directory is not inside a git working tree.' }
}
$CernealaRoot = [IO.Path]::GetFullPath($CernealaRoot).TrimEnd('\', '/') + '\'
if (-not (Test-Path -LiteralPath (Join-Path $CernealaRoot 'Cerneala.csproj'))) { throw "No Cerneala.csproj in $CernealaRoot." }

$destinationFull = [IO.Path]::GetFullPath($Destination)

# The destination must not be inside any git working tree (see .DESCRIPTION).
$probe = $destinationFull
while ($probe -and -not (Test-Path -LiteralPath $probe -PathType Container)) { $probe = Split-Path -Parent $probe }
if ($probe) {
    $top = & git -C $probe rev-parse --show-toplevel 2>$null
    if ($LASTEXITCODE -eq 0) {
        throw "Destination '$destinationFull' is inside the git working tree '$top'. The root Cerneala.csproj globs **\*.crn, so an app there breaks the build with CERNEALAUI003. Use a folder outside every checkout, for example the session scratchpad."
    }
}

