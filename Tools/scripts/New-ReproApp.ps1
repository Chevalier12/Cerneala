$harnessTemplate = @'
// Fixed infrastructure of the reproduction app (generated by Tools/scripts/New-ReproApp.ps1).
// The scenario lives in MainWindow.crn.cs; this file normally needs no edit.
using System.Reflection;
using Cerneala.Drawing;
using Cerneala.UI.Controls;
using Cerneala.UI.Invalidation;
using Cerneala.UI.Media;
using Cerneala.UI.Servo;
using ServoApi = Cerneala.UI.Servo.Servo;

namespace Issue@@N@@;

/// <summary>Result of one invariant check. Passed = false is the bug. Totals and Now are shown while the app runs.</summary>
public sealed record ReproCheckResult(bool Passed, string? Failure, string Totals, string Now);

/// <summary>One action of check mode: a description for the window and the GIF, and the Servo action itself.</summary>
public sealed record ReproStep(string Description, Func<ServoApi, Task> Action);

/// <summary>Thrown when the condition that triggers the bug never happened. Check mode turns it into exit code 2.</summary>
public sealed class ReproNotReachedException(string message) : Exception(message);

/// <summary>The text blocks of MainWindow.crn that the harness writes to.</summary>
public sealed record ReproView(
    TextBlock Verdict,
    TextBlock FirstFailure,
    TextBlock Totals,
    TextBlock Now,
    TextBlock Scale,
    TextBlock Step,
    TextBlock UserSteps,
    TextBlock Expected);

/// <summary>What the scenario (MainWindow.crn.cs) provides to the harness.</summary>
public interface IReproScenario
{
    /// <summary>Builds the scenario in the window and gives targets their Servo ids. Called once, in ContentRendered.</summary>
    void ReproSetUp();

    /// <summary>The numbered actions the user does, as literal text.</summary>
    string ReproUserSteps { get; }

    /// <summary>What the user sees when the bug is absent.</summary>
    string ReproExpected { get; }

    /// <summary>True when the checked state changed since the last invariant check (must be true before the first check).</summary>
    bool ReproCheckedStateChanged();

    /// <summary>Reads live framework state through public API and checks the broken invariant.</summary>
    ReproCheckResult ReproCheckInvariant();

    /// <summary>The actions check mode performs with Servo, in order.</summary>
    IReadOnlyList<ReproStep> ReproCheckSteps(ReproHarness harness);

    /// <summary>After all steps: null when the triggering condition happened, otherwise the reason it did not (exit code 2).</summary>
    string? ReproNotReached() => null;
}

public sealed class ReproHarness
{
    public const int Issue = @@N@@;
    public const int FrameCap = 300;

    private static readonly SolidColorBrush OkBrush = new(Color.FromRgb(0x48, 0xD6, 0x78));
    private static readonly SolidColorBrush BugBrush = new(Color.FromRgb(0xFF, 0x50, 0x50));
    private static readonly SolidColorBrush WaitBrush = new(Color.FromRgb(0xFF, 0xCA, 0x64));

    private readonly Window window;
    private readonly IReproScenario scenario;
    private readonly ReproView view;
    private string? firstFailure;
    private string totals = "Nothing checked yet.";
    private string now = "";
    private string? notReachedText;
    private bool started;

    public ReproHarness(Window window, IReproScenario scenario, ReproView view)
    {
        this.window = window;
        this.scenario = scenario;
        this.view = view;
    }

    private static string Variant =>
        Assembly.GetEntryAssembly()?
            .GetCustomAttributes<AssemblyMetadataAttribute>()
            .FirstOrDefault(attribute => attribute.Key == "ReproVariant")?.Value ?? "dev";

    private string VerdictFirstLine => firstFailure is null
        ? $"OK: bug #{Issue} does not reproduce so far."
        : $"BUG: bug #{Issue} reproduces.";

    /// <summary>Call once from ContentRendered.</summary>
    public void Start()
    {
        if (started)
        {
            return;
        }

        started = true;
        window.Title = Variant switch
        {
            "before" => $"Issue {Issue}: before the fix",
            "after" => $"Issue {Issue}: after the fix",
            _ => $"Issue {Issue}: dev build"
        };
        scenario.ReproSetUp();
        SetText(view.UserSteps, scenario.ReproUserSteps);
        SetText(view.Expected, scenario.ReproExpected);
        window.FrameRendered += (_, _) => Evaluate(force: false);
        Evaluate(force: true);

        string[] args = Environment.GetCommandLineArgs();
        int check = Array.IndexOf(args, "--check");
        if (check >= 0 && check + 1 < args.Length)
        {
            int frames = Array.IndexOf(args, "--frames");
            string? framesFolder = frames >= 0 && frames + 1 < args.Length ? args[frames + 1] : null;
            _ = RunCheckAsync(args[check + 1], framesFolder);
        }
    }

    /// <summary>
    /// Waits until the scenario's state is visible on the elements. Keeps frames coming while it waits and stops after
    /// <see cref="FrameCap"/> frames with a NOT REACHED result. Never count frames instead of waiting for state.
    /// </summary>
    public async Task WaitForStateAsync(ServoApi servo, Func<bool> condition, string description)
    {
        for (int frame = 0; frame < FrameCap; frame++)
        {
            if (condition())
            {
                return;
            }

            window.Invalidate(InvalidationFlags.Render, "Repro: wait for state");
            await servo.WaitForIdleAsync();
        }

        if (!condition())
        {
            throw new ReproNotReachedException($"State not reached after {FrameCap} frames: {description}.");
        }
    }

    private void Evaluate(bool force)
    {
        if (!force && !scenario.ReproCheckedStateChanged())
        {
            return;
        }

        ReproCheckResult result = scenario.ReproCheckInvariant();
        if (!result.Passed)
        {
            firstFailure ??= result.Failure ?? "The invariant failed.";
        }

        totals = result.Totals;
        now = result.Now;
        UpdateView();
    }

    private void UpdateView()
    {
        SetText(view.Verdict, notReachedText ?? VerdictFirstLine);
        Brush brush = firstFailure is not null ? BugBrush : notReachedText is not null ? WaitBrush : OkBrush;
        if (!ReferenceEquals(view.Verdict.Foreground, brush))
        {
            view.Verdict.Foreground = brush;
        }

        SetText(view.FirstFailure, firstFailure ?? "No failure so far.");
        SetText(view.Totals, totals);
        SetText(view.Now, now);
        SetText(view.Scale, $"Display scale: {window.Root?.Scale ?? 1:0.##}");
    }

    private static void SetText(TextBlock block, string text)
    {
        if (block.Text != text)
        {
            block.Text = text;
        }
    }

    private async Task RunCheckAsync(string reportFile, string? framesFolder)
    {
        int exitCode;
        string report;
        try
        {
            ServoApi servo = new(window, new ServoOptions { DefaultTimeout = TimeSpan.FromSeconds(30) });
            await servo.WaitForIdleAsync();
            IReadOnlyList<ReproStep> steps = scenario.ReproCheckSteps(this);
            int frame = 0;

            async Task Settle()
            {
                for (int i = 0; i < 3; i++)
                {
                    window.Invalidate(InvalidationFlags.Render, "Repro: settle");
                    await servo.WaitForIdleAsync();
                }
            }

            async Task Shot()
            {
                if (framesFolder is null)
                {
                    return;
                }

                Directory.CreateDirectory(framesFolder);
                window.Invalidate(InvalidationFlags.Render, "Repro: screenshot");
                await servo.WaitForIdleAsync();
                await servo.SaveScreenshotAsync(Path.Combine(framesFolder, $"frame-{frame++:000}.png"));
            }

            try
            {
                SetText(view.Step, "Check mode: start.");
                await Settle();
                await Shot();
                for (int i = 0; i < steps.Count; i++)
                {
                    SetText(view.Step, $"Check mode, step {i + 1} of {steps.Count}: {steps[i].Description}");
                    await steps[i].Action(servo);
                    await servo.WaitForIdleAsync();
                    await Settle();
                    await Shot();
                }

                notReachedText = firstFailure is null && scenario.ReproNotReached() is { } reason
                    ? "NOT REACHED: " + reason
                    : null;
            }
            catch (ReproNotReachedException exception)
            {
                notReachedText = "NOT REACHED: " + exception.Message;
            }

            Evaluate(force: true);
            exitCode = firstFailure is not null ? 1 : notReachedText is not null ? 2 : 0;
            string verdict = notReachedText ?? VerdictFirstLine;
            SetText(view.Step, $"Check mode finished: {verdict}");
            UpdateView();
            await Settle();
            await Shot();
            report = string.Join(Environment.NewLine,
                verdict,
                firstFailure ?? "No failure so far.",
                totals,
                now,
                view.Scale.Text);
        }
        catch (Exception exception)
        {
            exitCode = 3;
            report = "ERROR: " + exception;
        }

        File.WriteAllText(reportFile, report);
        Environment.ExitCode = exitCode;
        window.Close();
    }
}
'@

