namespace Cerneala.UI.Controls.Primitives;

// As WPF's AutoToolTipPlacement: where a Slider shows the tooltip with its value while the thumb is dragged. TopLeft is
// above a horizontal thumb and left of a vertical one, BottomRight is below a horizontal thumb and right of a vertical one.
public enum AutoToolTipPlacement
{
    None,
    TopLeft,
    BottomRight
}
